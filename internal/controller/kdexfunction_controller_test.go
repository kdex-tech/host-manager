			// First reconcile reaches SourceAvailable via the regenerate=false
			// short-circuit (today's behavior — backwards-compatible for
			// never-codegen'd functions where no input hash is recorded).
			Eventually(func(g Gomega) {
				fetched := &kdexv1alpha1.KDexFunction{}
				g.Expect(k8sClient.Get(ctx, client.ObjectKey{Name: resource.Name, Namespace: namespace}, fetched)).To(Succeed())
				g.Expect(fetched.Status.State).To(Equal(kdexv1alpha1.KDexFunctionStateSourceAvailable))
			}, "10s", "1s").Should(Succeed())

			// Now simulate "this function has been codegen-managed before, and
			// the input hash recorded then doesn't match the current spec.api."
			// Pre-set a stale hash + reset state to BuildValid to re-enter
			// handleBuildValid with edgeMode=true.
			fetched := &kdexv1alpha1.KDexFunction{}
			Expect(k8sClient.Get(ctx, client.ObjectKey{Name: resource.Name, Namespace: namespace}, fetched)).To(Succeed())
			patch := client.MergeFrom(fetched.DeepCopy())
			if fetched.Status.Attributes == nil {
				fetched.Status.Attributes = map[string]string{}
			}
			fetched.Status.Attributes["kdex.dev/codegen-input-api-hash"] = "stale-hash-from-prior-codegen"
