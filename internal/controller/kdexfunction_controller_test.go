			Expect(k8sClient.Status().Patch(ctx, fetched, patch)).To(Succeed())

			// Post-fix: handleBuildValid sees observed hash != current hash and
			// enters the codegen branch. Without a git secret in the test
			// environment, codegen degrades — state stays at BuildValid and
			// Degraded becomes True. This is the observable signal that
			// codegen was triggered by the input-hash change, not by the
			// regenerate flag (which is false).
